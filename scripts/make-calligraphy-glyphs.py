#!/usr/bin/env python3
"""Turns the letters of the bundled Cinzel Decorative font (SIL Open Font License, src/ui/title-screen/fonts/OFL.txt) into the
outline data the prologue's calligraphy is drawn from: src/engine/shadow/pure/calligraphy-glyphs.ts. Run once, by hand, when the
characters the story needs change; the game reads the data, not the font, so it needs no font library.

  python3 -m venv /tmp/venv && /tmp/venv/bin/pip install fonttools brotli
  /tmp/venv/bin/python scripts/make-calligraphy-glyphs.py
"""
import os
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FONT = os.path.join(ROOT, 'src/ui/title-screen/fonts/cinzel-decorative-latin-400-normal.woff2')
OUT = os.path.join(ROOT, 'src/engine/shadow/pure/calligraphy-glyphs.ts')
# Every character the story's lines use (letters, a space and the few marks).
CHARS = ("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz.,'’!?-")
EM = 1000  # the data is scaled to a 1000-unit em
STEPS = 5  # straight pieces a curve is cut into


class Flatten(BasePen):
    """Collects each outline as a list of points (a curve becomes STEPS short straight pieces)."""

    def __init__(self, glyph_set, scale):
        super().__init__(glyph_set)
        self.scale = scale
        self.contours = []
        self.current = None

    def _moveTo(self, p):
        self.current = [p]

    def _lineTo(self, p):
        self.current.append(p)

    def _qCurveToOne(self, c, p):
        p0 = self.current[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            self.current.append(((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * c[0] + t * t * p[0],
                                 (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * c[1] + t * t * p[1]))

    def _curveToOne(self, c1, c2, p):
        p0 = self.current[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            u = 1 - t
            self.current.append((u ** 3 * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t ** 3 * p[0],
                                 u ** 3 * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t ** 3 * p[1]))

    def _closePath(self):
        if self.current and len(self.current) > 2:
            self.contours.append(self.current)
        self.current = None

    def _endPath(self):
        self._closePath()


def main():
    font = TTFont(FONT)
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    per_em = font['head'].unitsPerEm
    scale = EM / per_em
    hmtx = font['hmtx']
    rows = []
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name is None:
            print('missing', ch)
            continue
        pen = Flatten(glyphs, scale)
        glyphs[name].draw(pen)
        contours = []
        for c in pen.contours:
            pts = []
            for x, y in c:
                pts.extend([round(x * scale), round(y * scale)])
            contours.append(pts)
        rows.append((ch, round(hmtx[name][0] * scale), contours))
    asc = round(font['hhea'].ascent * scale)
    lines = [
        '// GENERATED by scripts/make-calligraphy-glyphs.py from the Cinzel Decorative font (SIL Open Font License, see',
        '// src/ui/title-screen/fonts/OFL.txt). Do not edit by hand. The letters\' outlines, for the prologue\'s calligraphy to trace.',
        '// Each glyph: its advance, and its outlines as flat [x, y, x, y, ...] lists in a 1000-unit em, y up from the baseline.',
        '',
        'export interface CalligraphyGlyph {',
        '  readonly advance: number;',
        '  readonly contours: readonly (readonly number[])[];',
        '}',
        '',
        f'export const CALLIGRAPHY_EM = {EM};',
        f'export const CALLIGRAPHY_ASCENT = {asc};',
        'export const CALLIGRAPHY_SPACE = %d;' % round(hmtx[cmap[ord(' ')]][0] * scale),
        '',
        'export const CALLIGRAPHY_GLYPHS: Readonly<Record<string, CalligraphyGlyph>> = {',
    ]
    for ch, adv, contours in rows:
        key = ch.replace('\\', '\\\\').replace("'", "\\'")
        body = ', '.join('[' + ','.join(str(v) for v in c) + ']' for c in contours)
        lines.append(f"  '{key}': {{ advance: {adv}, contours: [{body}] }},")
    lines.append('};')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    size = os.path.getsize(OUT)
    print(f'{len(rows)} glyphs, {size} bytes -> {OUT}')


main()
